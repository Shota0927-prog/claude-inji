"""BTE-1 — ZoneEnginePracticalBTCUSD.pine: dedicated BTCUSD Engine library.

Source: ZoneEnginePracticalGBPJPY.pine, the source of the published ZoneEnginePracticalGBPJPY/3 that the BTC Visual /
Strategy imported (the file was last changed in 73fce49 (GBE-4 Merge Nearby) and the next GBPJPY commit 8e94720 "import the
published Merge Nearby Library as version 3" switched the imports to /3; gbe_build.IMPORT_GBE records /3).
Only the library name and one header comment change (same types, defaults, functions, computation and API).
strip_engine() reverses the edits and must give the GBPJPY source back byte for byte (fixture bte_sim).
The BTC Visual / Strategy import switch lives in btc_build (EDITS4) / btcs_build (EDITS3).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENG_SRC, ENG_PATH = "ZoneEnginePracticalGBPJPY.pine", "ZoneEnginePracticalBTCUSD.pine"
BASE_REV = "e1c3cea"     # the BTC Visual / Strategy before the split

ENGINE_EDITS = [
    ("header",
     "//  ZoneEnginePractical  —  Practical Zone v1 (Support / Resistance Zone Engine)\n",
     "//  ZoneEnginePractical  —  Practical Zone v1 (Support / Resistance Zone Engine)\n"
     "//  ★ BTCUSD 専用 (ZoneEnginePracticalBTCUSD、生成: tests/bte_build.py、BTE-1)。公開版 ZoneEnginePracticalGBPJPY/3 の\n"
     "//    ソース (ZoneEnginePracticalGBPJPY.pine) と同じ処理・公開 API で、違いは Library 名だけ (fixture bte_sim が固定)。\n"
     "//    以下の「GBPJPY 派生」等は移植元の説明 (履歴)。\n"),
    ("name",
     'library("ZoneEnginePracticalGBPJPY", overlay = true)\n',
     'library("ZoneEnginePracticalBTCUSD", overlay = true)\n'),
]


def _apply(src, edits):
    out = src
    for _, a, b in edits:
        assert out.count(a) == 1, a[:80]
        out = out.replace(a, b)
    return out


def _revert(text, edits):
    out = text
    for _, a, b in reversed(edits):
        if out is None or out.count(b) != 1:
            return None
        out = out.replace(b, a)
    return out


_rd = lambda p: open(os.path.join(ROOT, p), encoding="utf-8").read()


def build_engine():
    return _apply(_rd(ENG_SRC), ENGINE_EDITS)


def strip_engine(t):
    return _revert(t, ENGINE_EDITS)


if __name__ == "__main__":
    open(os.path.join(ROOT, ENG_PATH), "w", encoding="utf-8").write(build_engine())
    print("written", ENG_PATH)


# ---- helpers for the older fixtures (they pin the BTC files / tests as they were before BTE-1) ---------------------------
def _show(rev, path):
    import subprocess
    return subprocess.run(["git", "-C", ROOT, "show", f"{rev}:{path}"], capture_output=True, text=True).stdout


def bte_pine_ok(path, rev):
    """True when a BTC Visual / Strategy file differs from `rev` exactly by the BTE-1 layer (BTC-4 / BTS-3)."""
    import btc_build as bb
    import btcs_build as sb
    strip = {bb.BTC_PATH: bb.strip_btc4, sb.BTS_PATH: sb.strip_bts3}.get(path)
    if strip is None:
        return False
    s = strip(_rd(path))
    return s is not None and s == _show(rev, path)


def unadapt(path, text):
    """a test / generator file with its BTE-1 edits reverted (unchanged for files not in TEST_ADAPT)."""
    out = __import__("xa_build").unadapt(path, text)     # XA-1 edits (later) are reverted first
    for a, b in reversed(TEST_ADAPT.get(path, [])):
        if out is None or out.count(b) != 1:
            return None
        out = out.replace(b, a)
    return out


def test_ok(path):
    """True when the file differs from BASE_REV only by its exact BTE-1 edits."""
    return (path in TEST_ADAPT or path in __import__("xa_build").TEST_ADAPT) and unadapt(path, _rd(path)) == _show(BASE_REV, path)


